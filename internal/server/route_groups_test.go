const testRouteGroups = "# Generated by scaffold/docker/render-caddy-routes.sh; do not edit.\n" +
	"admin\tadmin.{$DOMAIN}\n" +
	"bg_ward\tward.{$DOMAIN}\n" +
	"planka-users\tplanka.{$DOMAIN}\n" +
	"planka-users\tboards.{$DOMAIN}\n" +
	"prototypes\tnarrator.{$DOMAIN}\n" +
	"Bad Name\tx.{$DOMAIN}\n"

func routeGroupsServer(t *testing.T, manifest string) (*Server, *captureSender) {
	t.Helper()
	path := filepath.Join(t.TempDir(), "route-groups.tsv")
	if manifest != "" {
		if err := os.WriteFile(path, []byte(manifest), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return testServerWith(t, func(c *config.Config) { c.RouteGroupsFile = path })
}

func TestRouteGroupsManifestParsing(t *testing.T) {
	srv, _ := routeGroupsServer(t, testRouteGroups)
	got, ok := srv.routeGroups()
	if !ok {
		t.Fatal("manifest not read")
	}
	if _, has := got["admin"]; has {
		t.Error("reserved role 'admin' listed as a group")
	}
	if _, has := got["bad name"]; has {
		t.Error("invalid group name listed")
	}
	if h := strings.Join(got["planka-users"], ","); h != "boards.example.com,planka.example.com" {
		t.Errorf("planka-users hosts = %q", h)
	}
}

