// The manifests of a deployment where several apps read a group as their own
// role. air-db's editing side is guarded "airdb_admin admin" (rule a);
// narrator's "prototypes admin" likewise. Planka's groups are plain route
// groups, but the app maps them to roles and says so with a scaffold-groups
// marker, which the renderer flags "declared" (rule b). planka-users is
// listed without admin on the boards host and never declared, so it stays an
// ordinary group. bg_ward is a plain break-glass group.
const (
	appRoleRouteGroups = "# Generated by scaffold/docker/render-caddy-routes.sh; do not edit.\n" +
		"admin\tdb.{$DOMAIN}\n" +
		"airdb_admin\tdb.{$DOMAIN}\n" +
		"admin\tnarrator.{$DOMAIN}\n" +
		"prototypes\tnarrator.{$DOMAIN}\n" +
		"planka-admins\tplanka.{$DOMAIN}\n" +
		"planka-admins\tplanka.{$DOMAIN}\tdeclared\n" +
		"planka-users\tplanka.{$DOMAIN}\n" +
		"planka-users\tboards.{$DOMAIN}\n" +
		"bg_ward\tward.{$DOMAIN}\n"
	appRoleRouteAccess = "# Generated by scaffold/docker/render-caddy-routes.sh; do not edit.\n" +
		"db.{$DOMAIN}\tdomains\trch.org.au\n" +
		"db.{$DOMAIN}\tgroups\tairdb_admin admin\n" +
		"narrator.{$DOMAIN}\tgroups\tprototypes admin\n" +
		"planka.{$DOMAIN}\tgroups\tplanka-admins planka-users\n" +
		"boards.{$DOMAIN}\tgroups\tplanka-users\n" +
		"ward.{$DOMAIN}\tgroups\tbg_ward\n"
)

// appRoleServer builds a server reading both manifests, with adjust applied
// on top (nil for none).
func appRoleServer(t *testing.T, adjust func(*config.Config)) (*Server, *captureSender) {
	t.Helper()
	dir := t.TempDir()
	groups := filepath.Join(dir, "route-groups.tsv")
	access := filepath.Join(dir, "route-access.tsv")
	if err := os.WriteFile(groups, []byte(appRoleRouteGroups), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(access, []byte(appRoleRouteAccess), 0o600); err != nil {
		t.Fatal(err)
	}
	return testServerWith(t, func(c *config.Config) {
		c.RouteGroupsFile = groups
		c.RouteAccessFile = access
		if adjust != nil {
			adjust(c)
		}
	})
}

func TestRefusedTargetsFromManifestsAndEnv(t *testing.T) {
	srv, _ := appRoleServer(t, func(c *config.Config) {
		c.BreakGlassRefusedGroups = []string{"insights-admins", "Admin"}
	})
	got := srv.refusedTargets()
	for _, g := range []string{"airdb_admin", "prototypes", "planka-admins", "insights-admins"} {
		if got[g] != refusedAppRole {
			t.Errorf("%s: reason %q, want %q", g, got[g], refusedAppRole)
		}
	}
	for _, g := range []string{"planka-users", "bg_ward", "admin"} {
		if _, refused := got[g]; refused {
			t.Errorf("%s should not be a refused target (reserved roles have their own check)", g)
		}
	}
}

// (a) A group listed together with admin in a route's group rule is the app's
// administrator role; a card may not target it. The group set is read from
// ROUTE_ACCESS_FILE, which keeps each rule whole, since the route-groups
// manifest flattens a rule to one group per line.
func TestBreakGlassRefusesGroupListedWithAdmin(t *testing.T) {
	srv, sender := appRoleServer(t, nil)
	c := newClient(t, srv.Handler())
	loginAs(t, c, sender, "admin@example.com", nil)
	tok := extractCSRF(t, c.get("/admin/break/new", nil).Body.String())

	rec := c.postForm("/admin/break", url.Values{"csrf": {tok}, "label": {"Imaging"}, "group": {"airdb_admin"}})
	if rec.Code != http.StatusBadRequest {
		t.Fatalf("card targeting airdb_admin: %d, want 400", rec.Code)
	}
	if body := rec.Body.String(); !strings.Contains(body, "reads that group as one of its own roles") {
		t.Errorf("refusal page lacks the reason:\n%s", body)
	}
	if codes, _ := srv.store.ListBreakGlassCodes(context.Background()); len(codes) != 0 {
		t.Errorf("refused card was stored: %+v", codes)
	}
}

