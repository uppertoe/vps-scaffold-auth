// The reserved roles stay refused with their own message, and an ordinary
// group listed without admin and never declared is still allowed.
func TestBreakGlassReservedStillRefusedAndPlainGroupAllowed(t *testing.T) {
	srv, sender := appRoleServer(t, nil)
	c := newClient(t, srv.Handler())
	loginAs(t, c, sender, "admin@example.com", nil)
	tok := extractCSRF(t, c.get("/admin/break/new", nil).Body.String())

	for _, role := range []string{"admin", "user", "guest"} {
		rec := c.postForm("/admin/break", url.Values{"csrf": {tok}, "label": {"Role " + role}, "group": {role}})
		if rec.Code != http.StatusBadRequest || !strings.Contains(rec.Body.String(), "reserved roles") {
			t.Errorf("card targeting %q: %d, want 400 with the reserved-role message", role, rec.Code)
		}
	}
	for _, g := range []string{"planka-users", "bg_ward"} {
		rec := c.postForm("/admin/break", url.Values{"csrf": {tok}, "label": {"Card " + g}, "group": {g}})
		if rec.Code != http.StatusFound {
			t.Errorf("card targeting %q: %d, want a redirect (%s)", g, rec.Code, rec.Body.String())
		}
	}
	codes, _ := srv.store.ListBreakGlassCodes(context.Background())
	if len(codes) != 2 {
		t.Errorf("want the two plain-group cards stored, got %+v", codes)
	}
}

// The codes page offers the known groups; a refused one is shown but cannot
// be chosen, with the reason beside it. An existing card whose group has
// since become an application role is marked in the list.
func TestCodesPageMarksRefusedTargets(t *testing.T) {
	srv, sender := appRoleServer(t, nil)
	ctx := context.Background()
	if err := srv.store.CreateGroup(ctx, "reports_team", ""); err != nil {
		t.Fatal(err)
	}
	if _, err := srv.store.CreateBreakGlassCode(ctx, store.BreakGlassCode{Label: "Old", TargetGroup: "prototypes", Status: store.BreakGlassActive}); err != nil {
		t.Fatal(err)
	}
	c := newClient(t, srv.Handler())
	loginAs(t, c, sender, "admin@example.com", nil)
	body := c.get("/admin/break/new", nil).Body.String()

	for _, want := range []string{
		`<option value="airdb_admin" disabled>airdb_admin (used as an application role)</option>`,
		`<option value="planka-admins" disabled>planka-admins (used as an application role)</option>`,
		`<option value="planka-users">planka-users</option>`,
		`<option value="bg_ward">bg_ward</option>`,
		`<option value="reports_team">reports_team</option>`,
		`name="group_new"`,
	} {
		if !strings.Contains(body, want) {
			t.Errorf("codes page missing %q", want)
		}
	}
	if strings.Contains(body, `<option value="admin"`) {
		t.Error("a reserved role is offered as a target")
	}
	body = c.get("/admin/break", nil).Body.String()
	row := body[strings.Index(body, ">Old</a>"):]
	row = row[:strings.Index(row, "</small>")]
	if !strings.Contains(row, `>used as an application role</span>`) {
		t.Errorf("existing card targeting prototypes is not marked:\n%s", row)
	}
}

// A stranger (an address the allow-list does not admit, who can sign in only
// as a guest) cannot be made a member of a group that is an application
// role, on the confirmation page or by a direct request; a member of staff
// can, and the stranger can still join an ordinary group.
func TestGuestMembershipRefusedForAppRoleGroup(t *testing.T) {
	srv, sender := appRoleServer(t, nil)
	ctx := context.Background()
	for _, g := range []string{"airdb_admin", "planka-users"} {
		if err := srv.store.CreateGroup(ctx, g, ""); err != nil {
			t.Fatal(err)
		}
	}
	c := newClient(t, srv.Handler())
	loginAs(t, c, sender, "admin@example.com", nil)
	tok := extractCSRF(t, c.get("/admin/groups/new", nil).Body.String())

	// Pasting a stranger and a colleague: the page lists the stranger as not
	// addable and offers only the colleague.
	rec := c.postForm("/admin/groups/airdb_admin/members", url.Values{"csrf": {tok}, "emails": {strangerAddr + "\nstaff@example.com"}})
	if rec.Code != http.StatusOK {
		t.Fatalf("paste = %d, want the confirmation page", rec.Code)
	}
	body := rec.Body.String()
	for _, want := range []string{"Cannot be added (1)", "To be added (1)", `value="staff@example.com"`, "used as an application role"} {
		if !strings.Contains(body, want) {
			t.Errorf("confirmation page missing %q", want)
		}
	}
	if strings.Contains(body, `value="`+strangerAddr+`"`) {
		t.Error("the stranger is offered for adding")
	}

	// A direct request naming the stranger adds nothing.
	rec = c.postForm("/admin/groups/airdb_admin/members/confirm", url.Values{"csrf": {tok}, "add": {strangerAddr}})
	if rec.Code != http.StatusFound {
		t.Fatalf("confirm = %d", rec.Code)
	}
	if m, _ := srv.store.ListGroupMembers(ctx, "airdb_admin"); len(m) != 0 {
		t.Fatalf("stranger added to airdb_admin: %v", m)
	}
	if page := c.get("/admin/groups", nil).Body.String(); !strings.Contains(page, adminWarnings["members-refused"]) {
		t.Error("the groups page does not say why nothing was added")
	}

	// A member of staff is added, with the stranger in the same request left out.
	rec = c.postForm("/admin/groups/airdb_admin/members/confirm", url.Values{"csrf": {tok}, "add": {strangerAddr, "staff@example.com"}})
	if rec.Code != http.StatusFound {
		t.Fatalf("confirm = %d", rec.Code)
	}
	if m, _ := srv.store.ListGroupMembers(ctx, "airdb_admin"); len(m) != 1 || m[0] != "staff@example.com" {
		t.Errorf("airdb_admin members = %v, want only the staff member", m)
	}

	// An ordinary group still takes the stranger.
	rec = c.postForm("/admin/groups/planka-users/members/confirm", url.Values{"csrf": {tok}, "add": {strangerAddr}})
	if rec.Code != http.StatusFound {
		t.Fatalf("confirm = %d", rec.Code)
	}
	if m, _ := srv.store.ListGroupMembers(ctx, "planka-users"); len(m) != 1 || m[0] != strangerAddr {
		t.Errorf("planka-users members = %v, want the stranger", m)
	}
}

