package server

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/uppertoe/vps-scaffold-auth/internal/config"
)

const testRouteAccess = "# Generated by scaffold/docker/render-caddy-routes.sh; do not edit.\n" +
	"planka.{$DOMAIN}\tgroups\tplanka-admins planka-users\n" +
	"rvg.{$DOMAIN}\tpublic\tthe feed checks its own token\n" +
	"neverdrugs.{$DOMAIN}\tgroups\tbg_neverdrugs\n" +
	"neverdrugs.{$DOMAIN}\tdomains\trch.org.au mcri.edu.au\n" +
	"neverdrugs.{$DOMAIN}\tnetwork\trch\n" +
	"odd.{$DOMAIN}\tunknown-kind\tx\n" +
	"<b>.{$DOMAIN}\tsigned-in\t\n"

func routeAccessServer(t *testing.T) (*Server, *captureSender) {
	t.Helper()
	path := filepath.Join(t.TempDir(), "route-access.tsv")
	if err := os.WriteFile(path, []byte(testRouteAccess), 0o600); err != nil {
		t.Fatal(err)
	}
	return testServerWith(t, func(c *config.Config) { c.RouteAccessFile = path })
}

func TestRouteAccessParsing(t *testing.T) {
	srv, _ := routeAccessServer(t)
	sites := srv.routeAccess()
	hosts := []string{}
	for _, s := range sites {
		hosts = append(hosts, s.Host)
	}
	if got := strings.Join(hosts, " "); got != "<b>.example.com neverdrugs.example.com planka.example.com rvg.example.com" {
		t.Fatalf("hosts = %q", got)
	}
	nd := sites[1]
	if len(nd.Rules) != 3 || nd.Rules[0].Kind != "network" || nd.Rules[0].Values[0] != "RCH" || nd.Rules[2].Kind != "groups" {
		t.Errorf("neverdrugs rules = %+v", nd.Rules)
	}
}

func TestOverviewShowsWhoCanReachWhat(t *testing.T) {
	srv, sender := routeAccessServer(t)
	c := newClient(t, srv.Handler())
	loginAs(t, c, sender, "admin@example.com", nil)
	body := c.get("/admin/", nil).Body.String()
	for _, want := range []string{"Who can reach what", "Open to everyone", "the feed checks its own token", "Anyone on the RCH network", "Anyone signed in with an address at rch.org.au, mcri.edu.au", "planka-users"} {
		if !strings.Contains(body, want) {
			t.Errorf("overview missing %q", want)
		}
	}
	if strings.Contains(body, "<b>.") {
		t.Error("host rendered unescaped")
	}
}

